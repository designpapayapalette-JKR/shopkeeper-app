export function formatCurrencyLocale(amount: number, locale: string = i18n.language): string {
  const code = locale === "hi" || locale === "ta" || locale === "ml" || locale === "kn" || locale === "te" || locale === "mr" || locale === "gu" ? "en-IN" : "en-IN";
  return `₹${(amount || 0).toLocaleString(code, { maximumFractionDigits: 0 })}`;
}

export function formatDateLocale(date: Date | string, locale: string = i18n.language): string {
  const d = typeof date === "string" ? new Date(date) : date;
  if (isNaN(d.getTime())) return "";
  return d.toLocaleDateString(locale === "hi" ? "hi-IN" : "en-IN", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
}
